export function iconInner(kind) {
  return ICON_PATHS[kind] || ICON_PATHS.item;
}

// Full, self-contained <svg> string (sized + currentColor). Safe to inject via
// {@html} because the markup is fixed here — no user input ever flows in.
export function iconSvg(kind, size = 16, cls = 'kico') {
  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${iconInner(kind)}</svg>`;
}

// Map an attachment's mime/extension to a file-type icon kind.
const IMG_RE = /\.(png|jpe?g|gif|webp|avif|bmp|svg)$/i;
const VIDEO_RE = /\.mp4$/i;
export function attachmentIconKind(obj) {
  const mime = (obj?.mime || '').toLowerCase();
  const name = obj?.path || obj?.filename || '';
  if (mime.startsWith('image/') || IMG_RE.test(name)) return 'image';
  if (mime === 'video/mp4' || VIDEO_RE.test(name)) return 'video';
  if (mime === 'application/pdf' || /\.pdf$/i.test(name)) return 'pdf';
  return 'file';
}

// The icon kind for any entity id — attachments resolve to their file type.
export function entityIconKind(pkg, id) {
  const e = pkg?.entity(id);
  if (!e) return 'file';
  if (e.kind === 'attachment') return attachmentIconKind(e.obj);
  return e.kind;
}
